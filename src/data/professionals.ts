/**
 * בעלי מקצוע (Professionals) — local static directory data.
 *
 * There is no `professionals` table in Supabase yet (see supabase/schema.sql
 * — only profiles/sentences/completions and the shem-tov name-catalogue
 * migrations exist), so this mirrors the shape a future table would have
 * and ships as a static, in-memory dataset — the same "placeholder content,
 * trivial to replace" approach already used for the Hospital Bag / Baby Gear
 * / Leaving checklists (see their screens' own module comments). Swapping
 * this for a real fetch later means replacing `PROFESSIONALS` and the
 * `attrs`/`serviceModes`/`price`/`distanceKm` fields with real columns —
 * nothing in the filtering/sorting/search logic needs to change shape.
 */

export type ProfessionalCategory = "mohel" | "lactation" | "sleep" | "doula"

export type ServiceMode = "in_person" | "at_client_home" | "online"

export type Professional = {
  id: string
  category: ProfessionalCategory
  name: string
  /** Shown directly under the name on the card, e.g. "מוהל רפואי". */
  title: string
  /** Free-text display label, e.g. "תל אביב והסביבה". */
  areaLabel: string
  /** Filterable area value — see AREA_OPTIONS in filterOptions.ts. */
  area: string
  /** Mock distance in km from the person — no real geolocation exists yet. */
  distanceKm: number
  rating: number | null
  reviewCount: number
  /** ₪. Not every professional has published pricing — omit rather than guess. */
  price: number | null
  serviceModes: ServiceMode[]
  /** "coming_soon" and/or "accepting_new" — a professional can be both. */
  availability: ("coming_soon" | "accepting_new")[]
  /** Up to 2 short chips shown on the card — kept compact on purpose. */
  displayTags: string[]
  phone: string
  /**
   * Category-specific filterable fields, keyed by the field id used in
   * filterOptions.ts (e.g. "type", "venue", "specialty"). Generic on
   * purpose: it lets one filter UI and one matching function work for all
   * four categories instead of four bespoke ones.
   */
  attrs: Record<string, string[]>
}

